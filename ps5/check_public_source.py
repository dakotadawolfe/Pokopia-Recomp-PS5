#!/usr/bin/env python3
"""Reject known private game artifacts in staged files or outgoing Git commits.

This is an accidental-upload guard, not a complete asset/provenance audit.
Reads Git objects so unstaged edits cannot disguise staged private contents.
"""
import argparse
from pathlib import PurePosixPath
import subprocess
import sys


FIXTURES = {
    "runtime/tests/data/fixture_aarch64.elf": "40a7b7ca8d96425ab839f09843b2c188826030b4",
    "runtime/tests/data/fixture_nosections.elf": "cd1ff85bbb34bb5f50d93f162446c8917e7ac1af",
    "runtime/tests/data/fixture_relr.elf": "f065329d6975fe5934edc62f2148a3cf89b774a0",
}
PRIVATE_DIRS = {
    "game", "work", "build", "shader_cache", "shader-cache", "bc7_cache",
    "exefs", "romfs", "modules-compact",
}
PRIVATE_EXTENSIONS = {
    ".nso", ".nro", ".npdm", ".nca", ".nsp", ".xci", ".keys", ".fdata",
    ".spv", ".glslc", ".bc", ".ll", ".elf", ".self", ".prx", ".pkg",
    ".exe", ".dll", ".a", ".o", ".obj", ".pdb", ".bin", ".zip", ".7z",
}
PRIVATE_NAMES = {
    "shader-cache-manifest.json", "module-verification.json",
    "startup-inputs.json", "input-manifest.json",
}
GENERATED_HEADER = b"/* generated by nxrecomp -- do not edit */"


def git(*args):
    return subprocess.check_output(["git", *args])


def path_reason(path, oid):
    if path in FIXTURES and FIXTURES[path] == oid:
        return None
    name = PurePosixPath(path.lower())
    if PRIVATE_DIRS.intersection(name.parts[:-1]):
        return "private input/output directory"
    if name.suffix in PRIVATE_EXTENSIONS or name.name in PRIVATE_NAMES:
        return "private or compiled artifact"
    if name.suffix == ".dksh" and not path.startswith("tools/shaders/corpus/sascha_dksh/"):
        return "shader binary outside the documented open-source test corpus"
    return None


def content_reason(prefix):
    if prefix.startswith((b"\x7fELF", b"\x4f\x15\x3d\x1d", b"MZ")):
        return "executable contents (regardless of filename)"
    if prefix.startswith((b"NSO0", b"PFS0", b"\x03\x02\x23\x07", b"\x07\x23\x02\x03")):
        return "game container or compiled shader contents"
    if prefix[16:20] == b"NRO0":
        return "NRO contents"
    if prefix.lstrip(b"\xef\xbb\xbf\r\n \t").startswith(GENERATED_HEADER):
        return "lifted source generated by nxrecomp"
    return None


def outgoing_commits(lines):
    commits = set()
    for line in lines:
        fields = line.split()
        if len(fields) != 4:
            raise ValueError("Malformed pre-push input")
        _, local_oid, _, remote_oid = fields
        if set(local_oid) == {"0"}:  # Deleted remote ref.
            continue
        args = ["rev-list", local_oid]
        if set(remote_oid) != {"0"}:
            present = subprocess.run(
                ["git", "cat-file", "-e", remote_oid + "^{commit}"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            if present.returncode == 0:
                args.append("^" + remote_oid)
        commits.update(git(*args).decode().splitlines())
    return sorted(commits)


def entries(revision):
    if revision == "INDEX":
        for record in git("ls-files", "--stage", "-z").split(b"\0"):
            if record:
                meta, path = record.split(b"\t", 1)
                _, oid, stage = meta.split()
                if stage != b"0":
                    raise ValueError("Resolve the unmerged index before checking")
                yield path.decode("utf-8", "surrogateescape"), oid.decode()
    else:
        for record in git("ls-tree", "-r", "-z", revision).split(b"\0"):
            if record:
                meta, path = record.split(b"\t", 1)
                _, kind, oid = meta.split()
                if kind == b"blob":
                    yield path.decode("utf-8", "surrogateescape"), oid.decode()


def audit(revisions):
    checked = {}
    failures = set()
    process = subprocess.Popen(
        ["git", "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
    )
    try:
        for revision in revisions:
            for path, oid in entries(revision):
                reason = path_reason(path, oid)
                if reason:
                    failures.add((path, oid, reason))
                    continue
                if FIXTURES.get(path) == oid:
                    continue
                if oid not in checked:
                    process.stdin.write((oid + "\n").encode())
                    process.stdin.flush()
                    header = process.stdout.readline().split()
                    if len(header) != 3 or header[1] != b"blob":
                        raise ValueError("Could not read Git blob " + oid)
                    size = int(header[2])
                    prefix = process.stdout.read(min(size, 4096))
                    remaining = size - len(prefix)
                    while remaining:
                        chunk = process.stdout.read(min(remaining, 1024 * 1024))
                        if not chunk:
                            raise ValueError("Truncated Git blob " + oid)
                        remaining -= len(chunk)
                    if process.stdout.read(1) != b"\n":
                        raise ValueError("Invalid Git batch framing")
                    checked[oid] = content_reason(prefix)
                if checked[oid]:
                    failures.add((path, oid, checked[oid]))
    finally:
        process.stdin.close()
        process.stdout.close()
        status = process.wait()
    if status:
        raise ValueError("Git blob reader failed")
    for path, oid, reason in sorted(failures):
        print(f"BLOCKED {path!r} ({oid[:12]}): {reason}", file=sys.stderr)
    if failures:
        print("Keep game-derived outputs private; see ps5/RELEASE_REQUIREMENTS.md.", file=sys.stderr)
        return 1
    print(f"Source artifact check passed for {len(revisions)} Git snapshot(s).")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--index", action="store_true")
    mode.add_argument("--all", action="store_true", help="Check all reachable local history")
    mode.add_argument("--pre-push", action="store_true", help="Read Git pre-push refs from stdin")
    args = parser.parse_args()
    if args.index:
        revisions = ["INDEX"]
    elif args.all:
        revisions = git("rev-list", "--all").decode().splitlines()
    elif args.pre_push:
        revisions = outgoing_commits(sys.stdin)
    else:
        revisions = ["HEAD"]
    return audit(revisions)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"Source artifact check failed: {error}", file=sys.stderr)
        sys.exit(2)
